"""Unit tests for the opt-in CODEOWNERS build hook (Idea #18)."""

from __future__ import annotations

import sqlite3
from pathlib import Path
from unittest.mock import patch

from cerebrofy.commands.build import _sync_codeowners
from cerebrofy.config.loader import CerebrоfyConfig, GovernanceConfig
from cerebrofy.governance.codeowners import CodeownersResult


def _config() -> CerebrоfyConfig:
    return CerebrоfyConfig(
        lobes={"auth": "auth"},
        tracked_extensions=[".py"],
        governance=GovernanceConfig(auto_sync_codeowners=True),
    )


def test_sync_codeowners_writes_through_generator(tmp_path: Path) -> None:
    conn = sqlite3.connect(":memory:")
    result = CodeownersResult(
        content="# Auto-generated by cerebrofy governance\n",
        path=tmp_path / "CODEOWNERS",
        lobes=("auth",),
    )
    try:
        with patch("cerebrofy.commands.build.open_db", return_value=conn), patch(
            "cerebrofy.governance.codeowners.generate_codeowners",
            return_value=result,
        ) as generate, patch(
            "cerebrofy.governance.codeowners.write_codeowners"
        ) as write:
            _sync_codeowners(tmp_path, _config(), tmp_path / "db.sqlite")
    finally:
        conn.close()

    generate.assert_called_once()
    write.assert_called_once_with(result.path, result.content, repo_root=tmp_path)


def test_sync_codeowners_warns_when_file_is_manual(tmp_path: Path) -> None:
    conn = sqlite3.connect(":memory:")
    result = CodeownersResult(
        content="# Auto-generated by cerebrofy governance\n",
        path=tmp_path / "CODEOWNERS",
    )
    try:
        with patch("cerebrofy.commands.build.open_db", return_value=conn), patch(
            "cerebrofy.governance.codeowners.generate_codeowners",
            return_value=result,
        ), patch(
            "cerebrofy.governance.codeowners.write_codeowners",
            side_effect=FileExistsError("manual file"),
        ):
            _sync_codeowners(tmp_path, _config(), tmp_path / "db.sqlite")
    finally:
        conn.close()
    # The helper must not raise: build treats CODEOWNERS sync as best-effort.


def test_build_sync_is_opt_in_by_default() -> None:
    config = CerebrоfyConfig(lobes={}, tracked_extensions=[])
    assert config.governance.auto_sync_codeowners is False
