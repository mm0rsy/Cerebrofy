"""Unit tests for the ``cerebrofy governance`` CLI group (Idea #18)."""

from __future__ import annotations

import json
import sqlite3
from pathlib import Path
from unittest.mock import patch

import pytest
from click.testing import CliRunner

from cerebrofy.commands.governance import cerebrofy_governance
from cerebrofy.config.loader import CerebrоfyConfig, GovernanceConfig
from cerebrofy.db.schema import EDGES_DDL, NODES_DDL
from cerebrofy.errors import GitHubNotAuthenticatedError


def _db() -> sqlite3.Connection:
    conn = sqlite3.connect(":memory:")
    conn.execute(NODES_DDL)
    conn.execute(EDGES_DDL)
    conn.execute(
        "INSERT INTO nodes (id, name, file, type, line_start, line_end) "
        "VALUES ('auth/a.py::a1', 'a1', 'auth/a.py', 'function', 1, 2)"
    )
    conn.execute(
        "INSERT INTO nodes (id, name, file, type, line_start, line_end) "
        "VALUES ('api/b.py::b1', 'b1', 'api/b.py', 'function', 1, 2)"
    )
    conn.execute(
        "INSERT INTO edges (src_id, dst_id, rel_type) "
        "VALUES ('api/b.py::b1', 'auth/a.py::a1', 'EXTERNAL_CALL')"
    )
    return conn


def _config(*, strategy: str = "explicit") -> CerebrоfyConfig:
    return CerebrоfyConfig(
        lobes={"auth": "auth"},
        tracked_extensions=[".py"],
        governance=GovernanceConfig(strategy=strategy),
    )


def _write_team(root: Path) -> None:
    (root / ".cerebrofy").mkdir(parents=True, exist_ok=True)
    (root / ".cerebrofy" / "team.yaml").write_text(
        "lobes:\n  auth:\n    owners: ['alice@example.com']\n", encoding="utf-8"
    )


def _write_rules(root: Path, text: str) -> None:
    (root / ".cerebrofy").mkdir(parents=True, exist_ok=True)
    (root / ".cerebrofy" / "arch-rules.yaml").write_text(text, encoding="utf-8")


def _invoke(
    tmp_path: Path,
    args: list[str],
    *,
    config: CerebrоfyConfig | None = None,
    conn: sqlite3.Connection | None = None,
) -> object:
    runner = CliRunner()
    connection = conn or _db()
    with patch(
        "cerebrofy.commands.governance._resolve_root", return_value=tmp_path
    ), patch(
        "cerebrofy.commands.governance._load_config",
        return_value=config or _config(),
    ), patch(
        "cerebrofy.commands.governance._open_db", return_value=connection
    ):
        return runner.invoke(cerebrofy_governance, args)


def _invoke_closed(
    tmp_path: Path,
    args: list[str],
    *,
    config: CerebrоfyConfig | None = None,
) -> object:
    conn = _db()
    try:
        return _invoke(tmp_path, args, config=config, conn=conn)
    finally:
        conn.close()


