def test_suggest_reviewers_json(tmp_path: Path) -> None:
    _write_team(tmp_path)
    result = _invoke_closed(
        tmp_path, ["suggest-reviewers", "--format", "json"]
    )
    assert result.exit_code == 0, result.output
    payload = json.loads(result.output)
    assert payload["reviewers"][0]["email"] == "alice@example.com"
    assert payload["reviewers"][0]["role"] == "primary"


def test_suggest_reviewers_markdown(tmp_path: Path) -> None:
    _write_team(tmp_path)
    result = _invoke_closed(tmp_path, ["suggest-reviewers"])
    assert result.exit_code == 0, result.output
    assert "## Suggested Reviewers" in result.output
    assert "| primary | alice@example.com | auth |" in result.output


def test_suggest_reviewers_reports_gh_error(tmp_path: Path) -> None:
    with patch(
        "cerebrofy.commands.governance.changes_from_pr",
        side_effect=GitHubNotAuthenticatedError("run gh auth login"),
    ):
        result = _invoke_closed(tmp_path, ["suggest-reviewers", "--pr", "7"])
    assert result.exit_code == 1
    assert "[GH_NOT_AUTHENTICATED]" in result.output
    assert "gh auth login" in result.output


def test_suggest_reviewers_rejects_pr_and_diff_together(tmp_path: Path) -> None:
    result = _invoke_closed(
        tmp_path, ["suggest-reviewers", "--pr", "7", "--diff", "HEAD"]
    )
    assert result.exit_code == 2
    assert "mutually exclusive" in result.output


def test_changes_from_diff_error_is_usage_error(tmp_path: Path) -> None:
    with patch(
        "cerebrofy.commands.governance.changes_from_diff",
        side_effect=ValueError("bad revision"),
    ):
        result = _invoke_closed(tmp_path, ["suggest-reviewers", "--diff", "nope"])
    assert result.exit_code == 2
    assert "bad revision" in result.output


