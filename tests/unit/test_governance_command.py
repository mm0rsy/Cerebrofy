def test_generate_codeowners_dry_run_does_not_write(tmp_path: Path) -> None:
    _write_team(tmp_path)
    result = _invoke_closed(tmp_path, ["generate-codeowners", "--dry-run"])
    assert result.exit_code == 0, result.output
    assert "# Auto-generated by cerebrofy governance" in result.output
    assert "auth/ @alice" in result.output
    assert not (tmp_path / "CODEOWNERS").exists()


def test_generate_codeowners_writes_file(tmp_path: Path) -> None:
    _write_team(tmp_path)
    result = _invoke_closed(tmp_path, ["generate-codeowners"])
    assert result.exit_code == 0, result.output
    target = tmp_path / "CODEOWNERS"
    assert target.exists()
    assert "auth/ @alice" in target.read_text(encoding="utf-8")
    assert "wrote" in result.output


def test_generate_codeowners_refuses_manual_file(tmp_path: Path) -> None:
    _write_team(tmp_path)
    target = tmp_path / "CODEOWNERS"
    target.write_text("# hand maintained\n* @human\n", encoding="utf-8")
    result = _invoke_closed(tmp_path, ["generate-codeowners"])
    assert result.exit_code == 2
    assert "was not generated by cerebrofy governance" in result.output
    assert "@human" in target.read_text(encoding="utf-8")


def test_generate_codeowners_force_overwrites_manual_file(tmp_path: Path) -> None:
    _write_team(tmp_path)
    target = tmp_path / "CODEOWNERS"
    target.write_text("# hand maintained\n", encoding="utf-8")
    result = _invoke_closed(tmp_path, ["generate-codeowners", "--force"])
    assert result.exit_code == 0, result.output
    assert target.read_text(encoding="utf-8").startswith(
        "# Auto-generated by cerebrofy governance"
    )


def test_generate_codeowners_custom_output(tmp_path: Path) -> None:
    _write_team(tmp_path)
    target = tmp_path / ".github" / "CODEOWNERS"
    result = _invoke_closed(
        tmp_path, ["generate-codeowners", "--output", str(target)]
    )
    assert result.exit_code == 0, result.output
    assert target.exists()


def test_generate_codeowners_rejects_output_outside_repo(tmp_path: Path) -> None:
    _write_team(tmp_path)
    result = _invoke_closed(
        tmp_path, ["generate-codeowners", "--output", "../escaped-CODEOWNERS"]
    )
    assert result.exit_code == 2
    assert "outside the repository root" in result.output
    assert not (tmp_path.parent / "escaped-CODEOWNERS").exists()


