"""GitHub CODEOWNERS generation from lobe ownership + call-graph topology."""

from __future__ import annotations

import sqlite3
from dataclasses import dataclass
from datetime import date
from pathlib import Path

from cerebrofy.config.loader import CerebrоfyConfig
from cerebrofy.governance.ownership import (
    DEFAULT_FALLBACK_OWNER,
    LobeOwnership,
    TeamConfig,
    compute_all_lobe_ownership,
    cross_lobe_callers,
    load_team_config,
    max_blast_radius,
)

GENERATED_MARKER = "# Auto-generated by cerebrofy governance"
_GENERATED_HINT = (
    f"{GENERATED_MARKER} — DO NOT EDIT MANUALLY\n"
    "# Regenerate with `cerebrofy governance generate-codeowners`."
)
_MAX_CO_REVIEWERS = 3


@dataclass(frozen=True)
class CodeownersResult:
    """Rendered CODEOWNERS content plus the data used to build it."""

    content: str
    path: Path
    lobes: tuple[str, ...] = ()
    fallback_lobes: tuple[str, ...] = ()
    as_of: str = ""

    @property
    def lines(self) -> int:
        return len(self.content.splitlines())


def is_generated_codeowners(content: str) -> bool:
    """True when *content* was produced by this generator."""
    return GENERATED_MARKER in content.splitlines()[0] if content else False


def _owner_token(owner: str) -> str:
    value = owner.strip()
    if not value:
        return DEFAULT_FALLBACK_OWNER
    if value.startswith("@"):
        return value
    if "@" in value:
        local = value.split("@", 1)[0].strip()
        return f"@{local}" if local else DEFAULT_FALLBACK_OWNER
    return f"@{value}"


def _pattern(lobe: str, path: str) -> str:
    normalised = path.replace("\\", "/").strip("/")
    if normalised in ("", "."):
        return "*"
    return f"{normalised}/"


def _is_tests_lobe(lobe: str, path: str) -> bool:
    normalised = path.replace("\\", "/").strip("/")
    return (
        lobe.lower() == "tests"
        or normalised == "tests"
        or normalised.startswith("tests/")
    )


def _bus_factor_label(bus_factor: int) -> str:
    if bus_factor <= 1:
        return "critical"
    if bus_factor == 2:
        return "moderate"
    return "healthy"


def _fallback_owners(config: CerebrоfyConfig, team: TeamConfig) -> str:
    owner = team.default_owner or config.governance.fallback_owner
    return _owner_token(owner or DEFAULT_FALLBACK_OWNER)


def _shared_test_owners(
    profiles: dict[str, LobeOwnership],
    lobes: dict[str, str],
    team: TeamConfig,
    config: CerebrоfyConfig,
) -> str:
    owners: list[str] = []
    for lobe in sorted(profiles):
        profile = profiles[lobe]
        if _is_tests_lobe(lobe, lobes.get(lobe, "")):
            owners.extend(author.author for author in profile.authors)
        elif profile.primary:
            owners.append(profile.primary)
    if not owners:
        return _fallback_owners(config, team)
    deduped = sorted({_owner_token(owner) for owner in owners})
    return " ".join(deduped)


def generate_codeowners(
    conn: sqlite3.Connection,
    repo_root: Path,
    config: CerebrоfyConfig,
    *,
    strategy: str | None = None,
    as_of: str | None = None,
    ownership: dict[str, LobeOwnership] | None = None,
) -> CodeownersResult:
    """Render a CODEOWNERS file from ownership, bus factor, and cross-lobe calls."""
    effective_strategy = strategy or config.governance.strategy
    team = load_team_config(repo_root)
    if ownership is not None:
        profiles = ownership
    else:
        profiles = compute_all_lobe_ownership(
            conn,
            repo_root,
            config.lobes,
            strategy=effective_strategy,
            activity_days=config.governance.activity_days,
            team=team,
        )

    cross = cross_lobe_callers(conn, config.lobes)
    lobes = dict(config.lobes)
    output_date = as_of or date.today().isoformat()

    header = [
        f"{GENERATED_MARKER} — {output_date}",
        "# DO NOT EDIT MANUALLY — run `cerebrofy governance generate-codeowners` to update.",
        f"# Ownership strategy: {effective_strategy}",
        "# Owners are derived from git blame, team.yaml, and the call graph.",
        "",
    ]
    body: list[str] = []
    fallback_lobes: list[str] = []

    # GitHub CODEOWNERS is last-match-wins: the root ``*`` fallback must come
    # first, then increasingly specific patterns so the most specific wins.
    ordered = sorted(
        lobes,
        key=lambda name: (
            _pattern(name, lobes[name]) != "*",
            len(lobes[name].replace("\\", "/").strip("/")),
            name,
        ),
    )
    has_tests_lobe = any(_is_tests_lobe(lobe, path) for lobe, path in lobes.items())

    for lobe in ordered:
        path = lobes[lobe]
        pattern = _pattern(lobe, path)
        profile = profiles.get(lobe) or LobeOwnership(
            lobe=lobe, strategy=effective_strategy, path=path
        )
        display = path if path not in ("", ".") else "(root)"

        if _is_tests_lobe(lobe, path):
            shared_owners = _shared_test_owners(profiles, lobes, team, config)
            body.append(f"# {display}/ — Shared ownership")
            body.append(f"{pattern} {shared_owners}".rstrip())
            body.append("")
            continue

        if profile.primary is None:
            fallback_lobes.append(lobe)
            fallback = _fallback_owners(config, team)
            radius = max_blast_radius(conn, lobes, lobe=lobe)
            body.append(
                f"# {display}/ — New module (no commit history) — "
                f"assigned fallback owner {fallback}"
            )
            if radius:
                body.append(f"# blast_radius={radius} — requires senior review")
            body.append(f"{pattern} {fallback}")
            body.append("")
            continue

        owners = [_owner_token(profile.primary)]
        comments = [
            (f"# {display}/ — Bus Factor: {profile.bus_factor} "
            f"({_bus_factor_label(profile.bus_factor)}) — Primary: {profile.primary}")
        ]
        for caller in cross.get(lobe, ())[:_MAX_CO_REVIEWERS]:
            caller_profile = profiles.get(caller.caller_lobe)
            if caller_profile is None or caller_profile.primary is None:
                continue
            token = _owner_token(caller_profile.primary)
            if token in owners:
                continue
            owners.append(token)
            caller_path = lobes.get(caller.caller_lobe, caller.caller_lobe)
            comments.append(
                f"# Cross-lobe: {caller_path}/ makes {caller.count} call(s) here — "
                f"adding {caller.caller_lobe} owner as co-reviewer"
            )
        body.extend(comments)
        body.append(f"{pattern} {' '.join(owners)}")
        body.append("")

    if not has_tests_lobe and (repo_root / "tests").is_dir():
        shared_tests = _shared_test_owners(profiles, lobes, team, config)
        body.append("# tests/ — Shared ownership")
        body.append(f"tests/ {shared_tests}".rstrip())
        body.append("")

    content = "\n".join(header + body).rstrip() + "\n"
    return CodeownersResult(
        content=content,
        path=repo_root / "CODEOWNERS",
        lobes=tuple(sorted(lobes)),
        fallback_lobes=tuple(fallback_lobes),
        as_of=output_date,
    )


def _resolve_output(path: Path, repo_root: Path) -> Path:
    """Resolve *path* against *repo_root*, rejecting paths that escape it."""
    root = repo_root.resolve()
    candidate = path if path.is_absolute() else root / path
    resolved = candidate.resolve()
    try:
        resolved.relative_to(root)
    except ValueError:
        raise ValueError(
            f"Refusing to write CODEOWNERS outside the repository root: {resolved}"
        ) from None
    return resolved


def write_codeowners(
    path: Path,
    content: str,
    *,
    force: bool = False,
    repo_root: Path | None = None,
) -> None:
    """Write *content* to *path*, refusing to clobber a hand-maintained file.

    The generator owns any file carrying its header. A file without the header
    is treated as hand-maintained and requires ``force=True``. When
    *repo_root* is given, relative paths are resolved against it and paths that
    escape the repository are rejected.
    """
    target = _resolve_output(path, repo_root) if repo_root is not None else path
    if target.exists() and not force:
        existing = target.read_text(encoding="utf-8")
        if not is_generated_codeowners(existing):
            raise FileExistsError(
                f"{target} exists but was not generated by cerebrofy governance. "
                "Re-run with --force to overwrite it."
            )
    target.parent.mkdir(parents=True, exist_ok=True)
    # Atomic write: temp file + replace to avoid partial/truncated writes
    import tempfile
    with tempfile.NamedTemporaryFile(
        mode="w", encoding="utf-8", dir=target.parent, delete=False
    ) as tf:
        tf.write(content)
        tf.flush()
        import os
        os.fsync(tf.fileno())
        temp_path = Path(tf.name)
    try:
        temp_path.replace(target)
    finally:
        if temp_path.exists():
            temp_path.unlink(missing_ok=True)


